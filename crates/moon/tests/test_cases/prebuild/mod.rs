#[test]
fn test_pre_build_directory_placeholders() {
    let source_dir = "src";
    for directory in ["$pkg_dir/..".to_owned(), format!("$mod_dir/{source_dir}")] {
        let dir = TestDir::new_empty();
        let package = dir.join(source_dir).join("app");
        let assets = dir.join(source_dir).join("assets with spaces");
        std::fs::create_dir_all(&package).unwrap();
        std::fs::create_dir_all(&assets).unwrap();
        std::fs::write(
            dir.join("moon.mod"),
            format!("name = \"test/placeholders\"\nsource = {source_dir:?}\n"),
        )
        .unwrap();
        let moon = moon_bin();
        let program = if directory.starts_with("$pkg_dir") {
            ":embed".to_owned()
        } else {
            moonutil::shlex::join_native([moon.to_str().unwrap(), "tool", "embed"].into_iter())
        };
        let command = format!(
            "{program} --text -i \"{directory}/assets with spaces/./input.txt\" -o \"$pkg_dir/../app/generated.mbt\" --name resource"
        );
        std::fs::write(
            package.join("moon.pkg"),
            format!(
                "rule(name: \"embed\", command: {command:?})\ndev_build(rule: \"embed\", input: \"../assets with spaces/input.txt\", output: \"generated.mbt\")\n"
            ),
        )
        .unwrap();
        for text in ["before", "after"] {
            std::fs::write(assets.join("input.txt"), text).unwrap();
            moon_cmd(&dir)
                .args(["build", "--target", "wasm-gc"])
                .assert()
                .success();
            assert_eq!(
                read(package.join("generated.mbt")),
                format!(
                    "// Generated by `moon tool embed --text`, do not edit.\n\n///|\nlet resource : String =\n  #|{text}\n"
                ),
            );
        }
    }
}

#[test]
fn test_pre_build_combines_directory_and_file_placeholders() {
    let dir = TestDir::new_empty();
    std::fs::write(dir.join("moon.mod"), "name = \"test/placeholders\"\n").unwrap();
    std::fs::write(
        dir.join("moon.pkg"),
        r#"rule(name: "embed", command: ":embed --text -i \"$pkg_dir/$input\" -o \"$pkg_dir/$output\" --name resource")
dev_build(rule: "embed", input: "input.txt", output: "generated.mbt")
"#,
    )
    .unwrap();
    std::fs::write(dir.join("input.txt"), "embedded").unwrap();
    moon_cmd(&dir)
        .args(["build", "--target", "wasm-gc"])
        .assert()
        .success();
    expect![[r#"
        // Generated by `moon tool embed --text`, do not edit.

        ///|
        let resource : String =
          #|embedded
    "#]]
    .assert_eq(&read(dir.join("generated.mbt")));
}

#[test]
fn test_pre_build_equivalent_output_paths() {
    for absolute in [false, true] {
        let dir = TestDir::new_empty();
        let package = dir.join("app");
        std::fs::create_dir_all(&package).unwrap();
        std::fs::write(dir.join("moon.mod"), "name = \"test/output-identity\"\n").unwrap();
        let output = if absolute {
            dunce::canonicalize(&package)
                .unwrap()
                .join("generated.mbt")
                .to_str()
                .unwrap()
                .to_owned()
        } else {
            "../app/generated.mbt".to_owned()
        };
        std::fs::write(
            package.join("moon.pkg"),
            format!(
                r#"rule(name: "embed", command: ":embed --text -i $input -o $output --name resource")
dev_build(rule: "embed", input: "input.txt", output: {output:?})
"#,
            ),
        )
        .unwrap();

        for text in ["before", "after"] {
            std::fs::write(package.join("input.txt"), text).unwrap();
            moon_cmd(&dir)
                .args(["build", "--target", "wasm-gc"])
                .assert()
                .success();
            assert_eq!(
                read(package.join("generated.mbt")),
                format!(
                    "// Generated by `moon tool embed --text`, do not edit.\n\n///|\nlet resource : String =\n  #|{text}\n"
                ),
            );
        }
        build_graph::assert(
            moon_cmd(&dir).args(["build", "--target", "wasm-gc", "--dry-run"]),
            expect_file!["equivalent_output_paths.snap"],
        );
        // Formatting must recognize the same generated file, even when the
        // generator's output does not follow moonfmt's formatting conventions.
        let generated = "let generated:Int=1\n";
        std::fs::write(package.join("generated.mbt"), generated).unwrap();
        moon_cmd(&dir).arg("fmt").assert().success();
        assert_eq!(read(package.join("generated.mbt")), generated);
    }
}

