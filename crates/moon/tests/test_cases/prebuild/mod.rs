#[test]
#[cfg(windows)]
fn test_pre_build_parent_paths_with_long_source_root() {
    assert_pre_build_parent_paths(&"segment/".repeat(40));
}

fn assert_pre_build_parent_paths(source_dir: &str) {
    for (input, output, source, generated) in [
        (
            "../../share/workflow/change-review.mbtx",
            "generated.mbt",
            "share/workflow/change-review.mbtx",
            "agent_tool/mbtx/generated.mbt",
        ),
        (
            "input.txt",
            "../../share/workflow/generated.txt",
            "agent_tool/mbtx/input.txt",
            "share/workflow/generated.txt",
        ),
        #[cfg(windows)]
        (
            r"..\..\share\workflow\change-review.mbtx",
            "generated.mbt",
            "share/workflow/change-review.mbtx",
            "agent_tool/mbtx/generated.mbt",
        ),
        #[cfg(windows)]
        (
            "input.txt",
            r"../..\share/workflow\generated.txt",
            "agent_tool/mbtx/input.txt",
            "share/workflow/generated.txt",
        ),
    ] {
        let dir = TestDir::new_empty();
        let source_root = dir.join(source_dir);
        let package = source_root.join("agent_tool/mbtx");
        let shared = source_root.join("share/workflow");
        std::fs::create_dir_all(&package).unwrap();
        std::fs::create_dir_all(&shared).unwrap();
        #[cfg(windows)]
        if !source_dir.is_empty() {
            let canonical = dunce::canonicalize(&source_root).unwrap();
            let spelling = canonical.to_str().unwrap();
            assert!(spelling.encode_utf16().count() > 260);
            assert!(spelling.starts_with(r"\\?\"));
        }
        std::fs::write(
            dir.join("moon.mod"),
            format!("name = \"test/parent-paths\"\nsource = \"{source_dir}\"\n"),
        )
        .unwrap();
        std::fs::write(
            package.join("moon.pkg"),
            format!(
                r#"rule(name: "embed", command: ":embed --text -i $input -o $output --name workflow")
dev_build(rule: "embed", input: {input:?}, output: {output:?})
"#,
            ),
        )
        .unwrap();
        // Use the expected locations independently of the manifest spellings.
        let source = source_root.join(source);
        let generated = source_root.join(generated);
        assert!(!generated.exists());

        for text in ["before", "after"] {
            std::fs::write(&source, text).unwrap();
            // A short process cwd isolates path resolution from Windows'
            // separate limitation on launching children from long directories.
            moon_cmd(&dir)
                .arg("build")
                .arg(&package)
                .args(["--target", "native", "--release"])
                .assert()
                .success();
            assert_eq!(
                read(&generated),
                format!(
                    "// Generated by `moon tool embed --text`, do not edit.\n\n///|\nlet workflow : String =\n  #|{text}\n"
                ),
            );
        }
    }
}

