use colored::Colorize;
use std::io::Write;

use crate::runtest::TestStatistics;
use moonutil::test_metadata::MbtTestInfo;

#[derive(Clone, Debug)]
pub struct TestArgs {
    pub package: String,
    pub file_and_index: Vec<(String, Vec<std::ops::Range<u32>>)>,
}

impl TestArgs {
    /// Encode `filename:start-end,start-end/...` for all test runtimes.
    /// Compiler test metadata uses basenames, so `/` cannot occur in a name.
    /// Decoders split at the last `:` to preserve colons in Unix filenames.
    pub fn to_cli_args(&self) -> String {
        use std::fmt::Write;

        let mut args = String::new();
        for (file, ranges) in &self.file_and_index {
            let Some((first, rest)) = ranges.split_first() else {
                continue;
            };
            if !args.is_empty() {
                args.push('/');
            }
            write!(args, "{file}:{}-{}", first.start, first.end).unwrap();
            for range in rest {
                write!(args, ",{}-{}", range.start, range.end).unwrap();
            }
        }
        args
    }
}

/// Generates compact test output like: `[moontest/lib] my_test.mbt:25 "read should succeed" ok`
///
/// Note: This type was generated by an AI.
pub struct CompactTestFormatter<'a> {
    module_name: &'a str,
    stats: &'a TestStatistics,
    test_info: Option<&'a MbtTestInfo>,
}

impl<'a> CompactTestFormatter<'a> {
    pub fn new(
        module_name: &'a str,
        stats: &'a TestStatistics,
        test_info: Option<&'a MbtTestInfo>,
    ) -> Self {
        Self {
            module_name,
            stats,
            test_info,
        }
    }

    fn write_test_identifier<W: Write>(&self, w: &mut W) -> std::io::Result<()> {
        if let Some(info) = self.test_info {
            if let Some(name) = info.name.as_ref().filter(|n| !n.is_empty()) {
                write!(w, "{:?}", name)
            } else {
                write!(w, "#{}", info.index)
            }
        } else if !self.stats.test_name.is_empty() {
            write!(w, "{:?}", self.stats.test_name)
        } else {
            write!(w, "#{}", self.stats.index)
        }
    }

    fn write_common_prefix<W: Write>(&self, is_bench: bool, w: &mut W) -> std::io::Result<()> {
        // Try to strip the module prefix from the package name for brevity of output
        let stripped = self
            .stats
            .package
            .strip_prefix(self.module_name)
            .map(|x| x.strip_prefix('/').unwrap_or(x));
        // If we have stripped result, this is a local package and we print the module name only
        if stripped.is_some() {
            write!(w, "[{}] ", self.module_name)?;
        } else {
            write!(w, "[{}] ", self.stats.package)?;
        }
        if is_bench {
            write!(w, "bench ")?;
        } else {
            write!(w, "test ")?;
        }
        if let Some(subpackage) = stripped
            && !subpackage.is_empty()
        {
            write!(w, "{}/", subpackage)?;
        }
        write!(w, "{}", self.stats.filename)?;

        let line_number = self.test_info.and_then(|info| info.line_number);
        if let Some(line_num) = line_number {
            write!(w, ":{}", line_num)?;
            write!(w, " (")?;
            self.write_test_identifier(w)?;
            write!(w, ")")
        } else {
            write!(w, " ")?;
            self.write_test_identifier(w)
        }
    }

    pub fn write_success<W: Write>(&self, w: &mut W) -> std::io::Result<()> {
        self.write_common_prefix(false, w)?;
        write!(w, " {}", "ok".green().bold())
    }

    pub fn write_failure<W: Write>(&self, w: &mut W) -> std::io::Result<()> {
        self.write_common_prefix(false, w)?;
        write!(w, " {}", "failed".red().bold())
    }

    pub fn write_failure_with_message<W: Write>(
        &self,
        w: &mut W,
        message: &str,
    ) -> std::io::Result<()> {
        self.write_common_prefix(false, w)?;
        if message.is_empty() {
            write!(w, " {}", "failed".red().bold())
        } else {
            write!(w, " {}: {}", "failed".red().bold(), message)
        }
    }

    pub fn write_bench<W: Write>(&self, w: &mut W) -> std::io::Result<()> {
        self.write_common_prefix(true, w)?;
        write!(w, " {}", "ok".blue())
    }
}

#[cfg(test)]
mod tests {
    use super::TestArgs;

    #[test]
    #[allow(clippy::single_range_in_vec_init)]
    fn compact_test_args_group_ranges_without_changing_selection_order() {
        let args = TestArgs {
            package: "test/selection".into(),
            file_and_index: vec![
                ("empty.mbt".into(), vec![]),
                ("-Case:测试,e\u{301}.mbt".into(), vec![7..9, 0..2, 7..8]),
                ("{other}.mbt".into(), vec![1..2]),
                ("-Case:测试,e\u{301}.mbt".into(), vec![3..3]),
            ],
        };
        assert_eq!(
            args.to_cli_args(),
            "-Case:测试,e\u{301}.mbt:7-9,0-2,7-8/{other}.mbt:1-2/-Case:测试,e\u{301}.mbt:3-3"
        );
        assert_eq!(
            TestArgs {
                package: "test/selection".into(),
                file_and_index: vec![],
            }
            .to_cli_args(),
            ""
        );
    }
}
